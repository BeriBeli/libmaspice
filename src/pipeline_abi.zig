//! Fixed-width pipeline snapshot ABI. Caller owns Desktop throughout this
//! synchronous call; the returned value contains no borrowed handles or payloads.
const s = @import("root.zig");
const Desktop = @import("desktop_abi.zig").Desktop;
const Timing = extern struct { count: u64, p95_ms: f64, maximum_ms: f64, has_values: u32, reserved: u32 = 0 };
const Metrics = extern struct {
    display_channels: u64,
    damage_operations: u64,
    damage_bytes: u64,
    snapshots: u64,
    full_copy_bytes: u64,
    partial_copy_bytes: u64,
    direct_native_write_bytes: u64,
    cpu_materializations: u64,
    cpu_materialization_bytes: u64,
    pool_exhaustions: u64,
    in_flight_publications: u64,
    pool_in_use: u64,
    native_enabled: u64,
    allocated_frames: u64,
    allocated_bytes: u64,
    process_native_allocated_bytes: u64,
    gpu_copy_bytes: u64,
    gpu_errors: u64,
    native_video_frames: u64,
    recommended_working_set: u64,
    metal_allocated_bytes: u64,
    surface_bytes: u64,
    maximum_surface_bytes: u64,
    publisher_submissions: u64,
    publisher_snapshots: u64,
    publisher_emitted: u64,
    publisher_emitted_native: u64,
    publisher_emitted_cpu: u64,
    publisher_stale: u64,
    publisher_evictions: u64,
    publisher_coalesced: u64,
    publisher_prepared_coalesces: u64,
    publisher_suppressed: u64,
    publisher_flushes: u64,
    publisher_empty_flushes: u64,
    publisher_pending: u64,
    publisher_demanded: u64,
    publisher_prepared: u64,
    video_sessions: u64,
    video_hardware: u64,
    video_software: u64,
    video_query_failures: u64,
    video_decoded: u64,
    video_dropped: u64,
    video_materializations: u64,
    mjpeg_handles: u64,
    mjpeg_decoded: u64,
    mjpeg_native: u64,
    mjpeg_data_fallbacks: u64,
    mjpeg_allocations: u64,
    mjpeg_late: u64,
    mjpeg_superseded: u64,
    mjpeg_peak_buffers: u64,
    mjpeg_peak_decodes: u64,
    advanced_cpu_fallbacks: u64,
    native_fallbacks: u64,
    native_disables: u64,
