    receive_to_ready: Timing,
    ready_to_submit: Timing,
    flush_start_gap: Timing,
    flush_scheduling_delay: Timing,
    snapshot_duration: Timing,
    emit_duration: Timing,
};
pub export fn spice_zig_desktop_pipeline_metrics(handle: ?*Desktop, output: ?*Metrics) c_int {
    const self = handle orelse return -1;
    const destination = output orelse return -1;
    const value = self.diagnosticsSnapshot();
    destination.* = .{
        .display_channels = value.display_channels,
        .damage_operations = value.surfaces.damage_operations,
        .damage_bytes = value.surfaces.damage_bytes,
        .snapshots = value.surfaces.snapshots,
        .full_copy_bytes = value.surfaces.full_copy_bytes,
        .partial_copy_bytes = value.surfaces.partial_copy_bytes,
        .direct_native_write_bytes = value.surfaces.direct_native_write_bytes,
        .cpu_materializations = value.surfaces.cpu_materializations,
        .cpu_materialization_bytes = value.surfaces.cpu_materialization_bytes,
        .pool_exhaustions = value.surfaces.pool_exhaustions,
        .in_flight_publications = value.surfaces.publications,
        .pool_in_use = value.surfaces.pool_in_use,
        .native_enabled = @intFromBool(value.surfaces.native_enabled),
        .allocated_frames = value.surfaces.allocated_frames,
        .allocated_bytes = value.surfaces.allocated_bytes,
        .process_native_allocated_bytes = s.graphics.allocatedBytes(),
        .gpu_copy_bytes = value.surfaces.gpu_copy_bytes,
        .gpu_errors = value.surfaces.gpu_errors,
        .native_video_frames = value.surfaces.native_video_frames,
        .recommended_working_set = value.surfaces.recommended_working_set,
        .metal_allocated_bytes = value.surfaces.metal_allocated_bytes,
        .surface_bytes = value.surface_bytes,
        .maximum_surface_bytes = value.maximum_surface_bytes,
        .publisher_submissions = value.publisher.submissions,
        .publisher_snapshots = value.publisher.snapshots,
        .publisher_emitted = value.publisher.emitted,
        .publisher_emitted_native = value.publisher.emitted_native,
        .publisher_emitted_cpu = value.publisher.emitted_cpu,
        .publisher_stale = value.publisher.stale,
        .publisher_evictions = value.publisher.evictions,
        .publisher_coalesced = value.publisher.coalesced,
        .publisher_prepared_coalesces = value.publisher.prepared_coalesces,
        .publisher_suppressed = value.publisher.suppressed,
        .publisher_flushes = value.publisher.flushes,
        .publisher_empty_flushes = value.publisher.empty_flushes,
        .publisher_pending = value.publisher.pending,
        .publisher_demanded = value.publisher.demanded,
        .publisher_prepared = value.publisher.prepared,
        .video_sessions = value.streams.video_sessions,
        .video_hardware = value.streams.video_hardware,
        .video_software = value.streams.video_software,
        .video_query_failures = value.streams.video_query_failures,
        .video_decoded = value.streams.video_decoded,
        .video_dropped = value.streams.video_dropped,
        .video_materializations = value.streams.video_materializations,
        .mjpeg_handles = value.streams.mjpeg_handles,
        .mjpeg_decoded = value.streams.mjpeg_decoded,
        .mjpeg_native = value.streams.mjpeg_native,
        .mjpeg_data_fallbacks = value.streams.mjpeg_data_fallbacks,
        .mjpeg_allocations = value.streams.mjpeg_allocations,
        .mjpeg_late = value.streams.mjpeg_late,
        .mjpeg_superseded = value.streams.mjpeg_superseded,
        .mjpeg_peak_buffers = value.streams.mjpeg_peak_buffers,
        .mjpeg_peak_decodes = value.streams.mjpeg_peak_decodes,
        .advanced_cpu_fallbacks = value.streams.advanced_cpu_fallbacks,
        .native_fallbacks = value.streams.native_fallbacks,
        .native_disables = value.streams.native_disables,
        .first_disable_reason = if (value.streams.first_disable_reason) |reason| (if (reason == error.MetalUnavailable) @as(u64, 1) else 2) else 0,
        .batch_start_gap = timing(value.publisher.batch_start_gap),
        .framed_receive_batch_start_gap = timing(value.publisher.framed_receive_batch_start_gap),
        .receive_to_ready = timing(value.publisher.receive_to_ready),
        .ready_to_submit = timing(value.publisher.ready_to_submit),
        .flush_start_gap = timing(value.publisher.flush_start_gap),
        .flush_scheduling_delay = timing(value.publisher.flush_scheduling_delay),
        .snapshot_duration = timing(value.publisher.snapshot_duration),
        .emit_duration = timing(value.publisher.emit_duration),
    };
    return 0;
}
fn timing(histogram: s.timing.Histogram) Timing {
    const summary = histogram.summary();
    return .{ .count = summary.sample_count, .p95_ms = summary.p95_ms orelse 0, .maximum_ms = summary.maximum_ms orelse 0, .has_values = @intFromBool(summary.maximum_ms != null) };
}
